import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const json=p=>JSON.parse(read(p));
const assert=(c,m)=>{if(!c)throw new Error(m)};
const data=json('test/catalog-audit-v15.json');
const js=read('test/catalog-audit.js');
const cfg=read('test/app-config.js');
assert(data.version==='2026-08-22-prealpha-v15','Version des donnees audit catalogue inattendue');
assert(data.policy?.unknownModelsBlocked===true,'Les modeles non audites doivent etre bloques');
assert(data.policy?.discontinuedModelsBlocked===true,'Les modeles discontinués doivent etre bloques');
for(const brand of ['easton','victory','skylon']) assert(data.brands?.[brand]?.models,`Marque absente ${brand}`);
for(const m of ['x10','a/c/e','avance','avance sport','rx7','x7','x23','xx75 platinum plus','x10 parallel pro 4 mm','x10 parallel pro 3.2 mm','x10 protour','a/c/g','a/c/c','carbon one','apollo']) assert(data.brands.easton.models[m],`Easton non audite ${m}`);
for(const m of ['vap','vxt','vft','3dhv','v-tac 23','v-tac 25','v-tac 27','vx-27']) assert(data.brands.victory.models[m],`Victory non audite ${m}`);
for(const m of ['novice','radius','brixxon','performa','precium','paragon','preminens','bruxx','empros','quantic','instec','savage','edge','phoric','maverick','rove','ebony','frontier','bentwood']) assert(data.brands.skylon.models[m],`Skylon non audite ${m}`);
assert(data.brands.easton.models['a/c/g'].status==='discontinued','ACG doit rester discontinué');
assert(data.brands.easton.models['x10 protour'].recurve===false,'ProTour doit rester hors recurve');
assert(data.brands.skylon.models.edge.recurve===false,'Edge doit rester hors recurve');
assert(data.brands.skylon.models.novice.status==='audited_pending_selector','Novice ne doit pas etre auto-selectionnee sans table exacte');
assert(js.includes("const VERSION='Pré-alpha v16'"),'Version JS v16 absente');
assert(js.includes('injectAuditedEastonFamilies'),'Injection familles Easton absente');
for(const m of ["'x10'","'a/c/e'","'x10 parallel pro 4 mm'","'x10 parallel pro 3.2 mm'"]) assert(js.includes(m),`Famille Easton injectable absente ${m}`);
assert(js.includes('chooseNumericManufacturerSpine'),'Selection spine fabricant injection absente');
assert(js.includes('stockLength+1e-9<requestedLength'),'Garde-fou longueur fabricant injection absent');
assert(js.includes('rankRecommendation(rec,input)'),'Reclassement expert apres injection absent');
assert(js.includes('blockedStatus'),'Garde-fou statut absent');
assert(js.includes('non audité(s) écarté(s)'),'Message modele non audite absent');
assert(js.includes("model.replace(/premiens/i,'Preminens')"),'Correction Premiens absente');
assert(cfg.includes('catalog-audit.js?v=20260822-prealpha-v16'),'Boot audit v16 absent');
